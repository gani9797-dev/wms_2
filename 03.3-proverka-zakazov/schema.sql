-- Модуль 3.3 Проверка заказов

CREATE TABLE IF NOT EXISTS order_checks (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  doc_no VARCHAR(20) NOT NULL COMMENT 'ПРВ-0001',
  order_id BIGINT UNSIGNED NULL,
  checker_id BIGINT UNSIGNED NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'new' COMMENT 'new/ok/diff',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_chk_no (doc_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS order_check_items (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  check_id BIGINT UNSIGNED NOT NULL,
  sku VARCHAR(50) NOT NULL,
  plan_qty DECIMAL(12,3) NOT NULL DEFAULT 0,
  fact_qty DECIMAL(12,3) NOT NULL DEFAULT 0,
  KEY idx_ochi_chk (check_id),
  CONSTRAINT fk_ochi FOREIGN KEY (check_id) REFERENCES order_checks (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
