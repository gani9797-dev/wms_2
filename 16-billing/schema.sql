-- Модуль 16 «Биллинги» (3PL). Каноническая схема (MySQL 8 / MariaDB).
-- В рабочей БД таблицы создаются автоматически в shared/Billing.php
-- (billing_ensure_schema) для PostgreSQL/SQLite; здесь — эталон структуры.

CREATE TABLE IF NOT EXISTS billing_uom (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(20) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  precision INT NOT NULL DEFAULT 2
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS billing_calc_type (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  is_periodic TINYINT(1) NOT NULL DEFAULT 0,
  formula VARCHAR(255) NULL,
  description TEXT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS billing_service_group (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS billing_service (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(200) NOT NULL,
  group_id BIGINT UNSIGNED NULL,
  calc_type_id BIGINT UNSIGNED NULL,
  uom_id BIGINT UNSIGNED NULL,
  driver_code VARCHAR(30) NULL,
  event_type_code VARCHAR(40) NULL,
  default_price DECIMAL(18,4) NOT NULL DEFAULT 0,
  vat_rate DECIMAL(18,4) NOT NULL DEFAULT 20,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  comment TEXT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_bill_svc_event (event_type_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS billing_client (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  counterparty_id BIGINT UNSIGNED NULL,
  code VARCHAR(50) NULL,
  name VARCHAR(255) NOT NULL,
  inn VARCHAR(20) NULL,
  currency VARCHAR(10) NOT NULL DEFAULT 'RUB',
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS billing_tariff (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  client_id BIGINT UNSIGNED NOT NULL,
  number VARCHAR(32) NOT NULL,
  date_from DATE NOT NULL,
  date_to DATE NULL,
  currency VARCHAR(10) NOT NULL DEFAULT 'RUB',
  status VARCHAR(20) NOT NULL DEFAULT 'draft',
  period_type VARCHAR(20) NOT NULL DEFAULT 'month',
  cut_off_time VARCHAR(8) NOT NULL DEFAULT '23:59:59',
  storage_day_basis VARCHAR(20) NOT NULL DEFAULT 'END_OF_DAY',
  free_storage_days INT NOT NULL DEFAULT 0,
  rounding_rule VARCHAR(20) NOT NULL DEFAULT 'ROUND',
  rounding_rule_qty VARCHAR(20) NOT NULL DEFAULT 'NONE',
  min_charge_amount DECIMAL(18,4) NULL,
  notes TEXT NULL,
  version INT NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_bill_tr_client (client_id, date_from)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS billing_tariff_line (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  tariff_id BIGINT UNSIGNED NOT NULL,
  service_id BIGINT UNSIGNED NOT NULL,
  is_enabled TINYINT(1) NOT NULL DEFAULT 1,
  price DECIMAL(18,4) NOT NULL DEFAULT 0,
  min_charge DECIMAL(18,4) NULL,
  max_charge DECIMAL(18,4) NULL,
  discount_percent DECIMAL(18,4) NOT NULL DEFAULT 0,
  min_qty_threshold DECIMAL(18,4) NULL,
  free_qty DECIMAL(18,4) NOT NULL DEFAULT 0,
  date_from DATE NULL,
  date_to DATE NULL,
  comment TEXT NULL,
  KEY idx_bill_line_tariff (tariff_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS billing_tariff_tier (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  line_id BIGINT UNSIGNED NOT NULL,
  threshold_from DECIMAL(18,4) NOT NULL DEFAULT 0,
  threshold_to DECIMAL(18,4) NULL,
  price DECIMAL(18,4) NOT NULL DEFAULT 0,
  mode VARCHAR(20) NOT NULL DEFAULT 'VOLUME',   -- VOLUME | PROGRESSIVE
  basis VARCHAR(20) NOT NULL DEFAULT 'PER_DAY', -- PER_DAY | PER_PERIOD
  KEY idx_bill_tier_line (line_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS billing_event (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  external_id VARCHAR(100) NULL,
  source VARCHAR(20) NOT NULL DEFAULT 'MANUAL',
  client_id BIGINT UNSIGNED NOT NULL,
  event_type_code VARCHAR(40) NOT NULL,
  event_date DATE NOT NULL,
  quantity DECIMAL(18,4) NOT NULL DEFAULT 0,
  uom_code VARCHAR(20) NULL,
  sku VARCHAR(50) NULL,
  pallet_count DECIMAL(18,4) NOT NULL DEFAULT 0,
  box_count DECIMAL(18,4) NOT NULL DEFAULT 0,
  piece_count DECIMAL(18,4) NOT NULL DEFAULT 0,
  sticker_qty DECIMAL(18,4) NOT NULL DEFAULT 0,
  weight_kg DECIMAL(18,4) NOT NULL DEFAULT 0,
  volume_m3 DECIMAL(18,4) NOT NULL DEFAULT 0,
  doc_type VARCHAR(50) NULL,
  doc_no VARCHAR(100) NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'NEW',
  reason TEXT NULL,
  payload TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_bill_event_client (client_id, event_date),
  KEY idx_bill_event_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS billing_stock_daily (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  client_id BIGINT UNSIGNED NOT NULL,
  service_id BIGINT UNSIGNED NOT NULL,
  uom_code VARCHAR(20) NULL,
  day DATE NOT NULL,
  qty_start DECIMAL(18,4) NOT NULL DEFAULT 0,
  qty_in DECIMAL(18,4) NOT NULL DEFAULT 0,
  qty_out DECIMAL(18,4) NOT NULL DEFAULT 0,
  qty_billable DECIMAL(18,4) NOT NULL DEFAULT 0,
  is_free_day TINYINT(1) NOT NULL DEFAULT 0,
  day_no INT NOT NULL DEFAULT 0,
  price DECIMAL(18,4) NOT NULL DEFAULT 0,
  amount_net DECIMAL(18,4) NOT NULL DEFAULT 0,
  charge_id BIGINT UNSIGNED NULL,
  tariff_id BIGINT UNSIGNED NULL,
  run_id BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_bill_stock_day (client_id, day)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS billing_charge (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  client_id BIGINT UNSIGNED NOT NULL,
  service_id BIGINT UNSIGNED NOT NULL,
  charge_date DATE NULL,
  period_from DATE NULL,
  period_to DATE NULL,
  quantity DECIMAL(18,4) NOT NULL DEFAULT 0,
  price DECIMAL(18,4) NOT NULL DEFAULT 0,
  amount_net DECIMAL(18,4) NOT NULL DEFAULT 0,
  vat_rate DECIMAL(18,4) NOT NULL DEFAULT 20,
  vat_amount DECIMAL(18,4) NOT NULL DEFAULT 0,
  amount_gross DECIMAL(18,4) NOT NULL DEFAULT 0,
  tariff_id BIGINT UNSIGNED NULL,
  tariff_line_id BIGINT UNSIGNED NULL,
  tier_id BIGINT UNSIGNED NULL,
  event_id BIGINT UNSIGNED NULL,
  stock_daily_id BIGINT UNSIGNED NULL,
  calc_trace TEXT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',  -- ACTIVE | SUPERSEDED | REVERSED
  adjustment_of_id BIGINT UNSIGNED NULL,
  run_id BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_bill_charge_client (client_id, charge_date),
  KEY idx_bill_charge_period (period_from, period_to)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS billing_period (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  client_id BIGINT UNSIGNED NULL,
  period_from DATE NOT NULL,
  period_to DATE NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'OPEN',  -- OPEN | CLOSED | REOPENED
  closed_at DATETIME NULL,
  control_json TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS billing_run (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  period_from DATE NOT NULL,
  period_to DATE NOT NULL,
  client_scope TEXT NULL,
  mode VARCHAR(20) NOT NULL DEFAULT 'FULL',   -- DRY_RUN | FULL
  status VARCHAR(20) NOT NULL DEFAULT 'DONE',
  started_at DATETIME NULL,
  finished_at DATETIME NULL,
  stats TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS billing_calendar (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  day DATE NOT NULL UNIQUE,
  is_working TINYINT(1) NOT NULL DEFAULT 1,
  surcharge_factor DECIMAL(18,4) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS billing_conversion (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  from_code VARCHAR(20) NOT NULL,
  to_code VARCHAR(20) NOT NULL,
  factor DECIMAL(18,4) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS billing_adj_reason (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE,
  name VARCHAR(200) NOT NULL,
  requires_document TINYINT(1) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
